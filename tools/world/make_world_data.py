#!/usr/bin/env python3
"""Turns Natural Earth's 1:110m land polygons into source/ui/WorldData.h.

    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
    python3 tools/world/make_world_data.py ne_110m_land.geojson source/ui/WorldData.h

Natural Earth is in the public domain (https://www.naturalearthdata.com).
Each outer ring becomes a run of points: longitude and latitude in hundredths
of a degree, as int16.
"""

import json
import sys


def main(source, destination):
    data = json.load(open(source))
    rings = []
    for feature in data["features"]:
        geometry = feature["geometry"]
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        for polygon in polygons:
            ring = polygon[0]  # outer ring; 110m land has no holes worth drawing
            if ring and ring[0] == ring[-1]:
                ring = ring[:-1]
            if len(ring) >= 3:
                rings.append(ring)

    points, starts = [], []
    for ring in rings:
        starts.append((len(points) // 2, len(ring)))
        for lon, lat in ring:
            points += [round(lon * 100), round(lat * 100)]

    lines = [
        "// Generated by tools/world/make_world_data.py from Natural Earth's 1:110m land",
        "// polygons (public domain, https://www.naturalearthdata.com). Don't edit.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace jamtaba::world",
        "{",
        "",
        "struct Ring",
        "{",
        "    int start; // index of the first point",
        "    int count;",
        "};",
        "",
        f"inline constexpr Ring rings[] = {{",
    ]
    lines += [f"    {{ {s}, {c} }}," for s, c in starts]
    lines += ["};", "", "/** Longitude, latitude pairs in hundredths of a degree. */", "inline constexpr std::int16_t points[] = {"]
    for i in range(0, len(points), 16):
        lines.append("    " + ", ".join(str(v) for v in points[i:i + 16]) + ",")
    lines += ["};", "", "} // namespace jamtaba::world", ""]
    open(destination, "w").write("\n".join(lines))
    print(f"{len(rings)} rings, {len(points) // 2} points -> {destination}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
